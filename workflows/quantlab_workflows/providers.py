"""LLM Provider abstraction and implementations for QuantLab Workflows (ADR 0008)."""

from __future__ import annotations

from collections.abc import Callable
from typing import Any, Protocol


class LLMProvider(Protocol):
    """Protocol for language model providers in QuantLab workflows."""

    def generate(self, prompt: str, system_prompt: str | None = None, **kwargs: Any) -> str:
        """Generate a response from the language model given a prompt.

        Parameters
        ----------
        prompt : str
            The user prompt or instruction to the model.
        system_prompt : str | None, optional
            Optional system instructions framing the agent's role.
        **kwargs : Any
            Additional provider-specific parameters (e.g. temperature).

        Returns
        -------
        str
            The textual response generated by the model.
        """
        ...


class MockLLMProvider:
    """Deterministic LLM provider for tests, offline development and CI.

    Parameters
    ----------
    responses : dict[str, str] | None, optional
        A dictionary mapping prompt substrings to predefined responses.
    default_response : str, optional
        Fallback response if no substring matches in `responses`.
    """

    def __init__(
        self,
        responses: dict[str, str] | None = None,
        default_response: str = "Mock analysis completed successfully.",
    ) -> None:
        self.responses = responses or {}
        self.default_response = default_response
        self.call_history: list[dict[str, Any]] = []

    def generate(self, prompt: str, system_prompt: str | None = None, **kwargs: Any) -> str:
        """Return the pre-configured response matching the prompt or the default."""
        self.call_history.append(
            {"prompt": prompt, "system_prompt": system_prompt, "kwargs": kwargs}
        )
        for key, value in self.responses.items():
            if key in prompt:
                return value
        return self.default_response


class CallableLLMProvider:
    """Wrapper that turns any callable into an LLMProvider.

    Parameters
    ----------
    fn : Callable[[str, str | None], str]
        Function taking (prompt, system_prompt) and returning a string.
    """

    def __init__(self, fn: Callable[[str, str | None], str]) -> None:
        self._fn = fn

    def generate(self, prompt: str, system_prompt: str | None = None, **kwargs: Any) -> str:
        """Invoke the wrapped callable."""
        return self._fn(prompt, system_prompt)
